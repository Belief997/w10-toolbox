# 表 7-11：I 宏块类型 index → (cbp, intra16x16 预测模式)；index 0 = I_NxN，25 = I_PCM
def i_mb_info(index):
    """返回 (is_pcm, is_intra16x16, cbp_luma, cbp_chroma, pred_mode)。"""
    if index == 0:
        return False, False, 0, 0, -1
    if index == 25:
        return True, False, 0, 0, -1
    k = index - 1                              # 0..23
    pred_mode = k & 3
    cbp_chroma = (k >> 2) % 3
    cbp_luma = 15 if k >= 12 else 0
    return False, True, cbp_luma, cbp_chroma, pred_mode


